// Vector "scenes" rasterized onto a pixel grid of any size, so the same picture
// gets more detailed as boards grow. Coordinates are normalized: u (0..1, right), v (0..1, down).

function rot(u, v, cx, cy, a) {
  const x = u - cx, y = v - cy, c = Math.cos(-a), s = Math.sin(-a);
  return [x * c - y * s, x * s + y * c];
}
function inPoly(u, v, pts) {
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i], [xj, yj] = pts[j];
    if ((yi > v) !== (yj > v) && u < ((xj - xi) * (v - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function segDist(u, v, x0, y0, x1, y1) {
  const dx = x1 - x0, dy = y1 - y0, l2 = dx * dx + dy * dy;
  const t = l2 ? Math.max(0, Math.min(1, ((u - x0) * dx + (v - y0) * dy) / l2)) : 0;
  return Math.hypot(u - (x0 + t * dx), v - (y0 + t * dy));
}

function painter() {
  const ops = [];
  const add = (test, k) => ops.push([test, k]);
  const D = {
    fill: k => add(() => true, k),
    rect: (x0, y0, x1, y1, k) => add((u, v) => u >= x0 && u <= x1 && v >= y0 && v <= y1, k),
    circ: (cx, cy, r, k) => add((u, v) => (u - cx) ** 2 + (v - cy) ** 2 <= r * r, k),
    ell: (cx, cy, rx, ry, k, a = 0) => add((u, v) => { const [x, y] = rot(u, v, cx, cy, a); return (x / rx) ** 2 + (y / ry) ** 2 <= 1; }, k),
    ring: (cx, cy, r0, r1, k, maxV = 9) => add((u, v) => { const d = Math.hypot(u - cx, v - cy); return d >= r0 && d < r1 && v <= maxV; }, k),
    poly: (pts, k) => add((u, v) => inPoly(u, v, pts), k),
    line: (x0, y0, x1, y1, wd, k) => add((u, v, cw) => segDist(u, v, x0, y0, x1, y1) <= Math.max(wd, cw * 1.02) / 2 + 1e-9, k),
    dot: (cx, cy, k) => add((u, v, cw) => Math.abs(u - cx) < cw * 0.5 && Math.abs(v - cy) < cw * 0.5, k),
    bands: (y0, y1, keys) => add((u, v) => v >= y0 && v < y1,
      (u, v) => keys[Math.min(keys.length - 1, Math.floor(((v - y0) / (y1 - y0)) * keys.length))]),
    when: (fn, k) => add(fn, k),
  };
  return { D, ops };
}

export function renderScene(scene, w, h, mirror = false) {
  const { D, ops } = painter();
  scene.draw(D);
  const keys = new Array(w * h).fill(null);
  const cw = 1 / Math.max(w, h);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    let u = (x + 0.5) / w; const v = (y + 0.5) / h;
    if (mirror) u = 1 - u;
    let k = null;
    for (const [test, key] of ops) if (test(u, v, cw)) k = typeof key === 'function' ? key(u, v) : key;
    keys[y * w + x] = k;
  }
  return keys;
}

